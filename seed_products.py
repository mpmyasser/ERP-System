    db = DBManager()
    session = db.get_session()
    
    try:
        lines = raw_data.strip().split('\n')
        for line in lines:
            parts = line.split('\t')
            if len(parts) < 2:
                continue
            
            code = parts[0].strip()
            name = parts[1].strip()
            size = parts[2].strip() if len(parts) > 2 else None
            
            # Determine Structure Type
            # Suffix 'A' -> Top, 'B' -> Bottom
            structure_type = 'Single'
            if code.endswith(' A'):
                structure_type = 'Set_Part_Top'
            elif code.endswith(' B'):
                structure_type = 'Set_Part_Bottom'
            
            # Check if exists
            existing = session.query(Product).filter_by(code=code).first()
            if existing:
                existing.name = name
                existing.size = size
                existing.structure_type = structure_type
                print(f"Updated: {code}")
            else:
                new_p = Product(
                    code=code,
                    name=name,
                    size=size,
                    structure_type=structure_type,
                    type='Final' if structure_type == 'Single' else 'Component'
                )
                session.add(new_p)
                print(f"Created: {code}")
        
        # Post-process: Create Parents for A/B sets if they don't exist
        # e.g. if 89 A and 89 B exist, create 89
        all_codes = [p[0] for p in session.query(Product.code).all()]
        for code in all_codes:
            if code.endswith(' A'):
                base_code = code[:-2]
                if base_code not in all_codes:
                    # Find names from one of them
                    sample = session.query(Product).filter_by(code=code).first()
                    parent = Product(
                        code=base_code,
                        name=sample.name,
                        size=sample.size,
                        structure_type='Set_Parent',
                        type='Final'
                    )
                    session.add(parent)
                    all_codes.append(base_code)
                    print(f"Auto-Created Parent: {base_code}")
                    
        session.commit()
        print("Seeding completed successfully.")
    except Exception as e:
        session.rollback()
        print(f"Error: {e}")
    finally:
        session.close()

